// ─── Module state ─────────────────────────────────────────────────────────

let _currentLocale = 'en';

export function setLanguage(lang) {
  _currentLocale = LOCALES[lang] ? lang : 'en';

  // Update nav labels in the DOM (if the sidebar is already rendered)
  const navMap = { dashboard: 'dashboard', templates: 'templates', settings: 'settings', admin: 'admin' };
  for (const [view, key] of Object.entries(navMap)) {
    const el = document.querySelector(`.nav-item[data-view="${view}"] .nav-label`);
    if (el) el.textContent = t(`nav.${key}`);
  }

  // Update the html[lang] attribute
  document.documentElement.lang = _currentLocale;
}

export function getCurrentLocale() {
  return _currentLocale;
}

/**
 * Translate a dot-notation key with optional {{param}} interpolation.
 * Falls back to 'en' if the key is missing in the current locale.
 *
 * @param {string} key   - e.g. 'dashboard.title'
 * @param {object} params - e.g. { count: 3 }
 * @returns {string}
 */
export function t(key, params) {
  const resolve = (locale) => {
    const parts = key.split('.');
    let node = LOCALES[locale];
    for (const part of parts) {
      if (node == null) return undefined;
      node = node[part];
    }
    return node;
  };

  let value = resolve(_currentLocale);
  if (value === undefined) value = resolve('en');
  if (value === undefined) return key; // final fallback: the key itself

  // Non-string values (e.g. arrays like welcomeChips) are returned as-is;
  // param interpolation only applies to strings.
  if (typeof value !== 'string') return value;

  if (params) {
    value = value.replace(/\{\{(\w+)\}\}/g, (_, k) =>
      params[k] !== undefined ? String(params[k]) : `{{${k}}}`
    );
  }

  return value;
}
